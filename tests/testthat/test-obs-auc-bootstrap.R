test_that("stratified bootstrap AUC agrees with empirical ROC and is reproducible", {
  d <- data.frame(y = rep(0:1, each = 5), s = c(1, 2, 3, 4, 5, 2, 3, 4, 5, 6))
  set.seed(42)
  a <- epi_auc_ci(d, y, s, bootstrap = 100)
  set.seed(42)
  b <- epi_auc_ci(d, y, s, bootstrap = 100)
  expect_equal(a, b)
  expect_equal(a$estimate, epi_roc_curve(d, y, s)$auc[1])
  expect_lte(a$conf_low, a$conf_high)
  set.seed(42)
  low <- epi_auc_ci(d, y, s, direction = "lower", bootstrap = 100)
  expect_equal(low$estimate, 1 - a$estimate)
  expect_equal(low$conf_low, 1 - a$conf_high)
  expect_equal(low$conf_high, 1 - a$conf_low)
})
test_that("AUC bootstrap checks input and handles tied scores", {
  d <- data.frame(y = c(0, 0, 1, 1), s = rep(1, 4))
  set.seed(7)
  z <- epi_auc_ci(d, y, s, bootstrap = 100)
  expect_equal(c(z$estimate, z$conf_low, z$conf_high), rep(.5, 3))
  expect_error(epi_auc_ci(d[1:3, ], y, s, bootstrap = 100), "two cases")
  expect_error(epi_auc_ci(d, y, s, bootstrap = 5), "bootstrap")
  d$s[1] <- NA
  expect_error(epi_auc_ci(d, y, s, bootstrap = 100), "score")
})
