test_that("Poisson scan finds elevated cluster and calibrates maxima", {
 d<-data.frame(x=c(0,1,10,11),y=0,cases=c(8,7,1,1),pop=100)
 set.seed(10); z<-epi_spatial_scan(d,x,y,cases,pop,radii=c(.1,1),nsim=99)
 expect_equal(z$observed,15); expect_equal(z$expected,8.5); expect_equal(z$relative_risk,7.5)
 expect_equal(z$log_likelihood_ratio,15*log(15/8.5)+2*log(2/8.5))
 expect_true(z$p_value>=.01 && z$p_value<=1)
 set.seed(10); expect_equal(epi_spatial_scan(d,x,y,cases,pop,c(.1,1),nsim=99)$p_value,z$p_value)
 expect_true(is.na(epi_spatial_scan(d,x,y,cases,pop,.1,nsim=0)$p_value))
 expect_error(epi_spatial_scan(transform(d,cases=0),x,y,cases,pop,.1,nsim=0),"positive total")
 expect_error(epi_spatial_scan(d,x,y,cases,pop,100,nsim=0),"No eligible")
})
