test_that("frequency functions calculate expected proportions and rates", {
 d <- data.frame(e=c(1,0,1,0), t=c(1,2,1,2))
 expect_equal(epi_incidence(d,e)$estimate,0.5)
 expect_equal(epi_prevalence(d,e)$estimate,0.5)
 expect_equal(epi_attack_rate(d,e,multiplier=100)$estimate,50)
 expect_equal(epi_person_time(d,e,t)$estimate,1/3)
 expect_error(epi_incidence(data.frame(e=c(1,NA)), e),"0/1")
 expect_error(epi_person_time(data.frame(e=0,t=0),e,t),"positive")
 expect_error(epi_incidence(dplyr::group_by(d,e),e),"Grouped")
})
