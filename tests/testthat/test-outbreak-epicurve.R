test_that("epicurve fills missing bins and keeps groups", {
  d <- data.frame(onset = as.Date("2024-01-01") + c(0, 0, 2), g = c("a", "b", "a"))
  z <- epi_epicurve(d, onset, group = g)
  expect_equal(nrow(z), 6L)
  expect_equal(z$cases, c(1L, 0L, 1L, 1L, 0L, 0L))
  expect_equal(sum(z$cases), 3L)
  z <- epi_epicurve(d, onset, start = as.Date("2023-12-31"), end = as.Date("2024-01-05"))
  expect_equal(nrow(z), 6L)
  expect_equal(sum(z$cases), 3L)
  expect_error(epi_epicurve(d, onset, start = as.Date("2024-01-02")), "enclose")
})
test_that("weekly bins begin on Monday even before 1970", {
  d <- data.frame(onset = as.Date(c("1969-12-31", "1970-01-01", "1970-01-05")))
  z <- epi_epicurve(d, onset, interval = "week")
  expect_equal(z$date, as.Date(c("1969-12-29", "1970-01-05")))
  expect_equal(z$cases, c(2L, 1L))
})
