test_that("renewal forecasts are reproducible and zero R absorbs", {
  d <- data.frame(cases = c(1, 2, 3, 4))
  set.seed(10)
  a <- epi_renewal_forecast(d, cases, c(.5, .5), horizon = 4, rt = 1.2, nsim = 500)
  set.seed(10)
  b <- epi_renewal_forecast(d, cases, c(.5, .5), horizon = 4, rt = 1.2, nsim = 500)
  expect_equal(a, b)
  expect_equal(a$step, 1:4)
  expect_true(all(a$lower <= a$median & a$median <= a$upper))
  z <- epi_renewal_forecast(d, cases, 1, horizon = 3, rt = 0, nsim = 100)
  expect_equal(z$mean, c(0, 0, 0))
  expect_equal(z$upper, c(0, 0, 0))
  set.seed(1)
  z <- epi_renewal_forecast(d, cases, 1, horizon = 2, rt_shape = 2, rt_rate = 1, nsim = 200)
  expect_true(all(z$mean > 0))
  expect_error(epi_renewal_forecast(d, cases, 1, rt = 1, rt_shape = 2, rt_rate = 1), "either")
  expect_error(epi_renewal_forecast(d, cases, c(.2, .2), rt = 1), "weights summing")
})
test_that("renewal forecast first-step simulated mean approaches theoretical value", {
  d <- data.frame(cases = c(1, 2, 4))
  set.seed(42)
  z <- epi_renewal_forecast(d, cases, weights = c(.75, .25), horizon = 1, rt = 2, nsim = 50000)
  expect_equal(z$mean, 2 * (4 * .75 + 2 * .25), tolerance = .08)
})
